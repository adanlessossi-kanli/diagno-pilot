"""
Property-based test for JSON-RPC 2.0 structural validity of MCP server responses.

Feature: guided-diagnosis-multi-agent, Property 2: Validité structurelle JSON-RPC 2.0

**Validates: Requirements 2.4, 3.1**

Property 2: For ALL MCP method calls (tools/list, tools/call, resources/list,
resources/read, prompts/list, prompts/get) with ANY valid parameters, the
JSON-RPC 2.0 response generated by the BaseMCPServer must contain the fields
`jsonrpc` (value "2.0") and `id` matching the request id, and either `result`
(for success) or `error` (for errors). If `error`, it must have `code` (int)
and `message` (str).
"""
from __future__ import annotations

import asyncio
import json

import pytest
from hypothesis import HealthCheck, given, settings
from hypothesis import strategies as st
from httpx import ASGITransport, AsyncClient

from backend.agents.mcp_servers.base_server import BaseMCPServer


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def parse_sse_response(text: str) -> dict:
    """Extract the JSON-RPC 2.0 payload from an SSE ``data:`` line."""
    for line in text.strip().split("\n"):
        if line.startswith("data:"):
            return json.loads(line[len("data:"):].strip())
    raise ValueError("No data line found in SSE response")


